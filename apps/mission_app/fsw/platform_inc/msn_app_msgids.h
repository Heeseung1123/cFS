/* MSN_APP message IDs */
#ifndef MSN_APP_MSGIDS_H
#define MSN_APP_MSGIDS_H

/* V1 Command Message IDs must be 0x18xx */
#define MSN_APP_CMD_MID     0x18D0
#define MSN_APP_SEND_HK_MID 0x18D1

/* V1 Telemetry Message IDs must be 0x08xx */
#define MSN_APP_HK_TLM_MID         0x08D0
#define MSN_APP_TEMP_TLM_MID       0x08D1
#define MSN_APP_DIAG_TLM_MID       0x08D2
#define MSN_APP_APP_STATUS_TLM_MID 0x08D3

#endif /* MSN_APP_MSGIDS_H */
