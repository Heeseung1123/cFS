/* MSN_APP message IDs */
#ifndef MSN_APP_MSGIDS_H
#define MSN_APP_MSGIDS_H

/* V1 Command Message IDs must be 0x18xx */
#define MSN_APP_CMD_MID     0x18C0
#define MSN_APP_SEND_HK_MID 0x18C1

/* V1 Telemetry Message IDs must be 0x08xx */
#define MSN_APP_HK_TLM_MID       0x08C0
#define MSN_APP_SENSOR_TLM_MID   0x08C1
#define MSN_APP_ANALYSIS_TLM_MID 0x08C2
#define MSN_APP_LOG_TLM_MID      0x08C3

#endif /* MSN_APP_MSGIDS_H */
